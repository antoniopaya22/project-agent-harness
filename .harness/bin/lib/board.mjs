// Generated views over the backlog: index.json (for agents) and BOARD.md (for humans).
// Both are byte-stable given the same task files, so a merge conflict is resolved by
// regenerating rather than by hand-editing.

import fs from 'node:fs';
import path from 'node:path';
import { HARNESS_VERSION, writeFileIfChanged, writeJson } from './util.mjs';
import { OPEN_STATUSES, STATUSES, isBlockedByDeps, loadAll, logEvent, pickNext, save as saveTask } from './tasks.mjs';

const STATUS_LABEL = {
  backlog: 'Backlog',
  ready: 'Listas para empezar',
  in_progress: 'En curso',
  in_review: 'En revisión',
  blocked: 'Bloqueadas',
  done: 'Hechas',
  cancelled: 'Canceladas',
};

export function indexPath(ctx) {
  return path.join(ctx.harnessDir, 'backlog', 'index.json');
}

export function boardPath(ctx) {
  return path.join(ctx.harnessDir, 'backlog', 'BOARD.md');
}

export function buildIndex(tasks) {
  const byId = new Map(tasks.map((t) => [t.id, t]));
  const counts = Object.fromEntries(STATUSES.map((s) => [s, 0]));
  for (const t of tasks) if (counts[t.status] !== undefined) counts[t.status] += 1;
  const next = pickNext(tasks);

  return {
    harness_version: HARNESS_VERSION,
    counts: { ...counts, total: tasks.length, open: tasks.filter((t) => OPEN_STATUSES.includes(t.status)).length },
    next: next ? next.id : null,
    tasks: tasks
      .slice()
      .sort((a, b) => a.id.localeCompare(b.id))
      .map((t) => ({
        id: t.id,
        title: t.title,
        type: t.type,
        status: t.status,
        priority: t.priority ?? 'medium',
        size: t.size ?? null,
        area: t.context?.area ?? null,
        parent: t.parent ?? null,
        depends_on: t.depends_on ?? [],
        blocked: isBlockedByDeps(t, byId),
        assignee: t.assignee ? `${t.assignee.kind}:${t.assignee.id}` : null,
        branch: t.branch ?? null,
        updated_at: t.updated_at,
      })),
  };
}

export function renderBoard(ctx, index) {
  const { project } = ctx;
  const lines = [];
  lines.push(`<!-- GENERATED by harness v${HARNESS_VERSION} from .harness/backlog/tasks/ — do not edit; run \`harness index\` -->`);
  lines.push('');
  lines.push(`# Tablero — ${project.project.name}`);
  lines.push('');
  lines.push(
    `${index.counts.total} tareas · ${index.counts.open} abiertas · ` +
      `${index.counts.done} hechas${index.counts.cancelled ? ` · ${index.counts.cancelled} canceladas` : ''}`,
  );
  lines.push('');
  lines.push('| Columna | Tareas |');
  lines.push('|---------|--------|');
  for (const s of STATUSES) {
    if (index.counts[s]) lines.push(`| ${STATUS_LABEL[s]} | ${index.counts[s]} |`);
  }
  lines.push('');

  for (const status of STATUSES) {
    const rows = index.tasks.filter((t) => t.status === status);
    if (rows.length === 0) continue;
    lines.push(`## ${STATUS_LABEL[status]} (${rows.length})`);
    lines.push('');
    lines.push('| Id | Tarea | Prioridad | Tamaño | Área | Notas |');
    lines.push('|----|-------|-----------|--------|------|-------|');
    for (const t of rows) {
      const notes = [];
      if (t.blocked) notes.push(`espera ${t.depends_on.join(', ')}`);
      if (t.assignee) notes.push(t.assignee);
      if (t.parent) notes.push(`de ${t.parent}`);
      lines.push(
        `| \`${t.id}\` | ${escapeCell(t.title)} | ${t.priority} | ${t.size ?? '—'} | ${t.area ?? '—'} | ${notes.join(' · ') || '—'} |`,
      );
    }
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push(
    'Este tablero se genera desde los ficheros JSON de `.harness/backlog/tasks/`. ' +
      'Para cambiar algo, se cambia la tarea y se ejecuta `harness index` — no se edita este fichero.',
  );
  lines.push('');
  return lines.join('\n');
}

function escapeCell(s) {
  return String(s).replace(/\|/g, '\\|');
}

/**
 * An epic's status follows its children.
 *
 * Keeping it by hand is bookkeeping that goes stale the moment nobody is looking, and it is
 * fully derivable. Note this does set `done` without a human saying so, which everywhere
 * else is forbidden — legitimately, because the human decisions already happened one level
 * down: an epic is only done when every child was closed by a person.
 */
export function deriveEpicStatus(epic, children) {
  if (children.length === 0) return epic.status;
  const has = (s) => children.some((c) => c.status === s);
  const every = (fn) => children.every(fn);

  if (every((c) => c.status === 'cancelled')) return 'cancelled';
  const live = children.filter((c) => c.status !== 'cancelled');
  if (live.length === 0) return 'cancelled';
  if (live.every((c) => c.status === 'done')) return 'done';
  if (has('in_progress') || has('in_review')) return 'in_progress';
  if (has('blocked') && !has('ready') && !has('in_progress')) return 'blocked';
  if (has('ready')) return 'ready';
  return 'backlog';
}

function applyEpicStatuses(ctx, tasks) {
  const byParent = new Map();
  for (const t of tasks) {
    if (!t.parent) continue;
    if (!byParent.has(t.parent)) byParent.set(t.parent, []);
    byParent.get(t.parent).push(t);
  }
  const changed = [];
  for (const epic of tasks.filter((t) => t.type === 'epic')) {
    const derived = deriveEpicStatus(epic, byParent.get(epic.id) || []);
    if (derived !== epic.status) {
      const from = epic.status;
      epic.status = derived;
      saveTask(ctx, epic);
      logEvent(ctx, epic.id, 'harness', 'status_changed', `${from} -> ${derived} (derivado de sus hijas)`);
      changed.push(`${epic.id}: ${from} -> ${derived}`);
    }
  }
  return changed;
}

/** @returns {{index: object, changed: string[], epics: string[]}} */
export function regenerate(ctx, { tasks = null } = {}) {
  const all = tasks || loadAll(ctx);
  const epics = applyEpicStatuses(ctx, all);
  const index = buildIndex(all);
  const changed = [];
  const before = safeRead(indexPath(ctx));
  writeJson(indexPath(ctx), index);
  if (before !== safeRead(indexPath(ctx))) changed.push(path.relative(ctx.root, indexPath(ctx)));
  if (writeFileIfChanged(boardPath(ctx), renderBoard(ctx, index))) {
    changed.push(path.relative(ctx.root, boardPath(ctx)));
  }
  return { index, changed, epics };
}

function safeRead(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}
